export type ExerciseMap = Record<string, Exercise>

export function buildExerciseMap(list: Exercise[]): ExerciseMap {
  return Object.fromEntries(list.map((e) => [e.id, e]))
}

/**
 * 組み込み種目だけのマップ。
 * ユーザーが追加した種目も含めたい場合は AppContext の exerciseMap を使う。
 */
export const BUILTIN_EXERCISE_MAP: ExerciseMap = buildExerciseMap(EXERCISES)

export function exerciseNameFrom(map: ExerciseMap, id: string): string {
  return map[id]?.name ?? id
}

/** 指定部位を主動筋とする種目 */
export function exercisesForMuscle(list: Exercise[], muscle: MuscleId): Exercise[] {
  return list.filter((e) => e.primary.includes(muscle))
}
